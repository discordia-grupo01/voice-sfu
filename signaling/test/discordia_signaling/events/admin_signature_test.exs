defmodule DiscordiaSignaling.Events.AdminSignatureTest do
  use ExUnit.Case, async: true

  alias DiscordiaSignaling.Events.AdminSignature

  @secret "test-secret"
  @suspended "admin.user_suspended"
  @reactivated "admin.user_reactivated"

  # Vectors generated with Sign() from discordia-events_contract (admin package).
  @suspended_signature "4e4e1885838edbda6e1964eedc9452fd5825874a6c280dba7f73a5f6400ba710"
  @reactivated_signature "79d9f8177d1a8f643952e70bdf2fde24dc2c891783eb36cb216c51a1b3f3649a"
  @whole_second_signature "f96b97d150be7091270411377493ba9ace9b58bfc2f782fd674f02fe639f3f16"

  defp event(overrides \\ %{}) do
    Map.merge(
      %{
        "event_id" => "evt-123",
        "occurred_at" => "2026-10-14T12:30:45.123456Z",
        "user_id" => "user-42",
        "version" => 3,
        "signature" => @suspended_signature
      },
      overrides
    )
  end

  test "accepts the signature generated by the Go Sign" do
    assert AdminSignature.verify(@suspended, event(), @secret)
  end

  test "accepts a timestamp without fractional seconds as the Go Sign formats it" do
    event =
      event(%{
        "event_id" => "evt-124",
        "occurred_at" => "2026-10-14T12:30:45Z",
        "version" => 4,
        "signature" => @whole_second_signature
      })

    assert AdminSignature.verify(@suspended, event, @secret)
  end

  test "rejects a signature made for another routing key" do
    refute AdminSignature.verify(@reactivated, event(), @secret)

    assert AdminSignature.verify(
             @reactivated,
             event(%{"signature" => @reactivated_signature}),
             @secret
           )

    refute AdminSignature.verify(
             @suspended,
             event(%{"signature" => @reactivated_signature}),
             @secret
           )
  end

  test "rejects a tampered field" do
    refute AdminSignature.verify(@suspended, event(%{"user_id" => "user-43"}), @secret)
    refute AdminSignature.verify(@suspended, event(%{"version" => 4}), @secret)
    refute AdminSignature.verify(@suspended, event(%{"event_id" => "evt-999"}), @secret)

    refute AdminSignature.verify(
             @suspended,
             event(%{"occurred_at" => "2026-10-14T12:30:45Z"}),
             @secret
           )
  end

  test "rejects a wrong secret" do
    refute AdminSignature.verify(@suspended, event(), "other-secret")
  end

  test "rejects an empty or missing secret even with a matching signature" do
    refute AdminSignature.verify(@suspended, event(), "")
    refute AdminSignature.verify(@suspended, event(), nil)
  end

  test "rejects missing, empty, malformed or non-hex signatures" do
    refute AdminSignature.verify(@suspended, Map.delete(event(), "signature"), @secret)
    refute AdminSignature.verify(@suspended, event(%{"signature" => ""}), @secret)
    refute AdminSignature.verify(@suspended, event(%{"signature" => nil}), @secret)
    refute AdminSignature.verify(@suspended, event(%{"signature" => "zz"}), @secret)

    refute AdminSignature.verify(
             @suspended,
             event(%{"signature" => String.upcase(@suspended_signature)}),
             @secret
           )
  end

  test "rejects events with missing or ill-typed fields" do
    refute AdminSignature.verify(@suspended, Map.delete(event(), "occurred_at"), @secret)
    refute AdminSignature.verify(@suspended, event(%{"version" => "3"}), @secret)
    refute AdminSignature.verify(@suspended, event(%{"version" => 3.0}), @secret)
    refute AdminSignature.verify(@suspended, event(%{"user_id" => ""}), @secret)
    refute AdminSignature.verify(@suspended, "not-a-map", @secret)
  end

  describe "server events" do
    @server_suspended "admin.server_suspended"
    @server_reactivated "admin.server_reactivated"
    @server_deletion_requested "admin.server_deletion_requested"

    # Vectors from discordia-events_contract v0.13.1 (admin/vectors_test.go),
    # computed outside Go: the subject of the signed text is the server_id.
    @server_suspended_signature "456c6e2a80ddba4e13664b26baac16f713e2cddea6af70435b522c66a495ca75"
    @server_whole_second_signature "a80f65168feb3ed64c2fa18290c868006fc4bb4a5445572c1e38d0880ba07468"
    @server_reactivated_signature "b081fcb4de1d6814961bfc77fa1d575058476adac3e057ca39e15dff0d52e30a"
    @server_deletion_signature "d21e2d8f886f4d176aa0a6b212737e305a7b63ee87a602235b131aa540e52bf5"

    defp server_event(overrides \\ %{}) do
      Map.merge(
        %{
          "event_id" => "evt-123",
          "occurred_at" => "2026-10-14T12:30:45.123456Z",
          "server_id" => "server-42",
          "version" => 3,
          "signature" => @server_suspended_signature
        },
        overrides
      )
    end

    test "accepts the signatures generated by the Go Sign for every server event" do
      assert AdminSignature.verify(@server_suspended, server_event(), @secret)

      assert AdminSignature.verify(
               @server_suspended,
               server_event(%{
                 "event_id" => "evt-124",
                 "occurred_at" => "2026-10-14T12:30:45Z",
                 "version" => 4,
                 "signature" => @server_whole_second_signature
               }),
               @secret
             )

      assert AdminSignature.verify(
               @server_reactivated,
               server_event(%{"signature" => @server_reactivated_signature}),
               @secret
             )

      assert AdminSignature.verify(
               @server_deletion_requested,
               server_event(%{"signature" => @server_deletion_signature}),
               @secret
             )
    end

    test "rejects a server signature under another routing key" do
      refute AdminSignature.verify(@server_reactivated, server_event(), @secret)
      refute AdminSignature.verify(@server_deletion_requested, server_event(), @secret)
      refute AdminSignature.verify(@suspended, server_event(), @secret)
    end

    test "rejects a tampered field, a wrong or an empty secret" do
      refute AdminSignature.verify(
               @server_suspended,
               server_event(%{"server_id" => "server-43"}),
               @secret
             )

      refute AdminSignature.verify(@server_suspended, server_event(%{"version" => 4}), @secret)

      refute AdminSignature.verify(
               @server_suspended,
               server_event(%{"event_id" => "evt-999"}),
               @secret
             )

      refute AdminSignature.verify(@server_suspended, server_event(), "other-secret")
      refute AdminSignature.verify(@server_suspended, server_event(), "")
      refute AdminSignature.verify(@server_suspended, server_event(), nil)
    end

    test "a server event needs a server_id, and a user_id is not enough" do
      user_shaped = server_event() |> Map.delete("server_id") |> Map.put("user_id", "server-42")

      refute AdminSignature.verify(@server_suspended, user_shaped, @secret)
      refute AdminSignature.verify(@server_suspended, server_event(%{"server_id" => ""}), @secret)
      refute AdminSignature.verify(@server_suspended, server_event(%{"server_id" => 42}), @secret)
    end

    test "an account event can't pass as a server event, nor the other way round" do
      account_as_server =
        event() |> Map.delete("user_id") |> Map.put("server_id", "user-42")

      refute AdminSignature.verify(@server_suspended, account_as_server, @secret)
      refute AdminSignature.verify(@suspended, server_event(), @secret)
    end
  end
end
