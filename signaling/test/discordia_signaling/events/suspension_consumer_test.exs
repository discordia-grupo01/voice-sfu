defmodule DiscordiaSignaling.Events.SuspensionConsumerTest do
  use ExUnit.Case, async: false

  import ExUnit.CaptureLog

  alias DiscordiaSignaling.Events.{SuspensionConsumer, SuspensionVersions}
  alias DiscordiaSignaling.Voice.{MembershipCache, VoiceSessionRegistry}

  @secret "test-secret"
  @key "admin.user_suspended"

  setup do
    previous_room_service_result =
      Application.get_env(:discordia_signaling, :test_room_service_result)

    Application.put_env(:discordia_signaling, :test_room_service_result, :ok)
    start_supervised!(SuspensionVersions)

    on_exit(fn ->
      if previous_room_service_result do
        Application.put_env(
          :discordia_signaling,
          :test_room_service_result,
          previous_room_service_result
        )
      else
        Application.delete_env(:discordia_signaling, :test_room_service_result)
      end
    end)

    :ok
  end

  defp join(user_id, room_id \\ "room-suspension") do
    VoiceSessionRegistry.replicate_presence(%{
      "event_type" => "voice.participant_joined",
      "occurred_at" => "2026-10-14T12:00:00Z",
      "server_id" => "server-1",
      "room_id" => room_id,
      "participant_id" => user_id,
      "name" => "Ada"
    })

    on_exit(fn ->
      VoiceSessionRegistry.replicate_presence(%{
        "event_type" => "voice.participant_left",
        "occurred_at" => "2026-10-14T12:30:00Z",
        "server_id" => "server-1",
        "room_id" => room_id,
        "participant_id" => user_id,
        "name" => "Ada"
      })
    end)
  end

  defp signed_event(user_id, version) do
    event = %{
      "event_id" => "evt-" <> user_id <> "-" <> Integer.to_string(version),
      "occurred_at" => "2026-10-14T12:30:45.5Z",
      "user_id" => user_id,
      "version" => version
    }

    text =
      Enum.join(
        [@key, event["event_id"], user_id, Integer.to_string(version), event["occurred_at"]],
        "\n"
      )

    signature = :crypto.mac(:hmac, :sha256, @secret, text) |> Base.encode16(case: :lower)
    Map.put(event, "signature", signature)
  end

  defp signed_payload(user_id, version), do: user_id |> signed_event(version) |> Jason.encode!()

  defp process(payload, secret \\ @secret),
    do: SuspensionConsumer.process_payload(@key, payload, secret)

  test "removes a connected user from their room on a valid signed event" do
    join("suspended-user")
    assert VoiceSessionRegistry.active_room("suspended-user") == "voice:room-suspension"

    assert :ack = process(signed_payload("suspended-user", 1))

    assert VoiceSessionRegistry.active_room("suspended-user") == nil
  end

  test "forgets the cached server memberships of the suspended user, and only theirs" do
    {:ok, agent} = Agent.start_link(fn -> 0 end)

    confirm = fn ->
      Agent.update(agent, &(&1 + 1))
      :ok
    end

    MembershipCache.clear()
    on_exit(&MembershipCache.clear/0)

    MembershipCache.fetch({"cached-user", "server-1"}, 60_000, confirm)
    MembershipCache.fetch({"other-user", "server-1"}, 60_000, confirm)
    assert Agent.get(agent, & &1) == 2

    assert :ack = process(signed_payload("cached-user", 1))

    # The suspended user is asked again; the other one is still remembered.
    MembershipCache.fetch({"cached-user", "server-1"}, 60_000, confirm)
    MembershipCache.fetch({"other-user", "server-1"}, 60_000, confirm)
    assert Agent.get(agent, & &1) == 3
  end

  test "a stale or duplicate suspension does not touch the cache" do
    {:ok, agent} = Agent.start_link(fn -> 0 end)

    confirm = fn ->
      Agent.update(agent, &(&1 + 1))
      :ok
    end

    MembershipCache.clear()
    on_exit(&MembershipCache.clear/0)

    assert :ack = process(signed_payload("stale-user", 2))
    MembershipCache.fetch({"stale-user", "server-1"}, 60_000, confirm)

    assert :ack = process(signed_payload("stale-user", 2))
    assert :ack = process(signed_payload("stale-user", 1))

    MembershipCache.fetch({"stale-user", "server-1"}, 60_000, confirm)
    assert Agent.get(agent, & &1) == 1
  end

  test "accepts the signature generated by the Go Sign" do
    join("user-42")

    payload =
      Jason.encode!(%{
        "event_id" => "evt-123",
        "occurred_at" => "2026-10-14T12:30:45.123456Z",
        "user_id" => "user-42",
        "version" => 3,
        "signature" => "4e4e1885838edbda6e1964eedc9452fd5825874a6c280dba7f73a5f6400ba710"
      })

    assert :ack = process(payload)
    assert VoiceSessionRegistry.active_room("user-42") == nil
  end

  test "acks a user who is not in any room" do
    assert :ack = process(signed_payload("idle-user", 1))
    refute SuspensionVersions.newer?("idle-user", 1)
  end

  test "acks when LiveKit no longer has the participant" do
    join("gone-user")
    Application.put_env(:discordia_signaling, :test_room_service_result, {:error, :not_found})

    assert :ack = process(signed_payload("gone-user", 1))
    assert VoiceSessionRegistry.active_room("gone-user") == nil
  end

  test "retries when LiveKit does not respond and does not record the version" do
    join("retry-user")
    Application.put_env(:discordia_signaling, :test_room_service_result, {:error, :unavailable})
    payload = signed_payload("retry-user", 1)

    assert :retry = process(payload)
    assert VoiceSessionRegistry.active_room("retry-user") == "voice:room-suspension"
    assert SuspensionVersions.newer?("retry-user", 1)

    Application.put_env(:discordia_signaling, :test_room_service_result, :ok)

    assert :ack = process(payload)
    assert VoiceSessionRegistry.active_room("retry-user") == nil
  end

  test "ignores a duplicate or older version while the process lives" do
    join("dup-user")
    assert :ack = process(signed_payload("dup-user", 2))
    assert VoiceSessionRegistry.active_room("dup-user") == nil

    join("dup-user")
    assert :ack = process(signed_payload("dup-user", 2))
    assert :ack = process(signed_payload("dup-user", 1))
    assert VoiceSessionRegistry.active_room("dup-user") == "voice:room-suspension"

    assert :ack = process(signed_payload("dup-user", 3))
    assert VoiceSessionRegistry.active_room("dup-user") == nil
  end

  test "acks and does nothing when the signature is missing, invalid or for another event" do
    join("safe-user")
    valid = signed_event("safe-user", 1)

    log =
      capture_log([level: :warning], fn ->
        for event <- [
              Map.delete(valid, "signature"),
              %{valid | "signature" => String.duplicate("0", 64)},
              %{valid | "user_id" => "someone-else"}
            ] do
          assert :ack = process(Jason.encode!(event))
        end

        assert :ack =
                 SuspensionConsumer.process_payload(
                   "admin.user_reactivated",
                   Jason.encode!(valid),
                   @secret
                 )
      end)

    assert VoiceSessionRegistry.active_room("safe-user") == "voice:room-suspension"
    assert SuspensionVersions.newer?("safe-user", 1)
    assert log =~ "voice_suspension_invalid_signature"
  end

  test "does not expel anyone when the secret is empty" do
    join("nosecret-user")

    capture_log([level: :warning], fn ->
      assert :ack = process(signed_payload("nosecret-user", 1), "")
    end)

    assert VoiceSessionRegistry.active_room("nosecret-user") == "voice:room-suspension"
  end

  test "discards broken JSON and events without a user_id" do
    assert :ack = process("not-json")
    assert :ack = process("[]")

    capture_log([level: :warning], fn ->
      assert :ack = process(signed_payload("", 1))
    end)
  end

  describe "server suspension" do
    @server_suspended "admin.server_suspended"
    @server_reactivated "admin.server_reactivated"

    defp join_server(user_id, room_id, server_id) do
      VoiceSessionRegistry.replicate_presence(%{
        "event_type" => "voice.participant_joined",
        "occurred_at" => "2026-10-14T12:00:00Z",
        "server_id" => server_id,
        "room_id" => room_id,
        "participant_id" => user_id,
        "name" => "Ada"
      })

      on_exit(fn ->
        VoiceSessionRegistry.replicate_presence(%{
          "event_type" => "voice.participant_left",
          "occurred_at" => "2026-10-14T12:30:00Z",
          "server_id" => server_id,
          "room_id" => room_id,
          "participant_id" => user_id,
          "name" => "Ada"
        })
      end)
    end

    defp signed_server_event(routing_key, server_id, version, secret \\ @secret) do
      event = %{
        "event_id" => "evt-" <> server_id <> "-" <> Integer.to_string(version),
        "occurred_at" => "2026-10-14T12:30:45.5Z",
        "server_id" => server_id,
        "version" => version
      }

      text =
        Enum.join(
          [routing_key, event["event_id"], server_id, Integer.to_string(version), event["occurred_at"]],
          "\n"
        )

      signature = :crypto.mac(:hmac, :sha256, secret, text) |> Base.encode16(case: :lower)
      Map.put(event, "signature", signature)
    end

    defp process_server(routing_key, event, secret \\ @secret),
      do: SuspensionConsumer.process_payload(routing_key, Jason.encode!(event), secret)

    defp suspend_server(server_id, version),
      do: process_server(@server_suspended, signed_server_event(@server_suspended, server_id, version))

    test "closes every room of the suspended server and leaves other servers alone" do
      join_server("sv-user-1", "sv-room-a", "sv-server-1")
      join_server("sv-user-2", "sv-room-a", "sv-server-1")
      join_server("sv-user-3", "sv-room-b", "sv-server-1")
      join_server("sv-user-4", "sv-room-c", "sv-server-2")

      assert :ack = suspend_server("sv-server-1", 1)

      for user <- ["sv-user-1", "sv-user-2", "sv-user-3"] do
        assert VoiceSessionRegistry.active_room(user) == nil
      end

      assert VoiceSessionRegistry.active_room("sv-user-4") == "voice:sv-room-c"
    end

    test "accepts the signature generated by the Go Sign" do
      join_server("sv-go-user", "sv-go-room", "server-42")

      event = %{
        "event_id" => "evt-123",
        "occurred_at" => "2026-10-14T12:30:45.123456Z",
        "server_id" => "server-42",
        "version" => 3,
        "signature" => "456c6e2a80ddba4e13664b26baac16f713e2cddea6af70435b522c66a495ca75"
      }

      assert :ack = process_server(@server_suspended, event)
      assert VoiceSessionRegistry.active_room("sv-go-user") == nil
    end

    test "forgets the cached memberships of that server only" do
      {:ok, agent} = Agent.start_link(fn -> 0 end)

      confirm = fn ->
        Agent.update(agent, &(&1 + 1))
        :ok
      end

      MembershipCache.clear()
      on_exit(&MembershipCache.clear/0)

      MembershipCache.fetch({"u1", "sv-cache-1"}, 60_000, confirm)
      MembershipCache.fetch({"u2", "sv-cache-1"}, 60_000, confirm)
      MembershipCache.fetch({"u1", "sv-cache-2"}, 60_000, confirm)
      assert Agent.get(agent, & &1) == 3

      assert :ack = suspend_server("sv-cache-1", 1)

      MembershipCache.fetch({"u1", "sv-cache-2"}, 60_000, confirm)
      assert Agent.get(agent, & &1) == 3

      MembershipCache.fetch({"u1", "sv-cache-1"}, 60_000, confirm)
      MembershipCache.fetch({"u2", "sv-cache-1"}, 60_000, confirm)
      assert Agent.get(agent, & &1) == 5
    end

    test "acks a server with no rooms and remembers the version" do
      assert :ack = suspend_server("sv-empty", 1)
      refute SuspensionVersions.newer?({:server, "sv-empty"}, 1)
    end

    test "a duplicate or older version expels nobody and leaves the cache alone" do
      join_server("sv-dup-user", "sv-dup-room", "sv-dup")
      assert :ack = suspend_server("sv-dup", 2)
      assert VoiceSessionRegistry.active_room("sv-dup-user") == nil

      # Back in the room (after a reactivation, say): the same or older versions
      # change nothing, a newer one expels again.
      join_server("sv-dup-user", "sv-dup-room", "sv-dup")
      assert :ack = suspend_server("sv-dup", 2)
      assert :ack = suspend_server("sv-dup", 1)
      assert VoiceSessionRegistry.active_room("sv-dup-user") == "voice:sv-dup-room"

      assert :ack = suspend_server("sv-dup", 3)
      assert VoiceSessionRegistry.active_room("sv-dup-user") == nil
    end

    test "retries while LiveKit does not respond, without recording the version" do
      join_server("sv-retry-user", "sv-retry-room", "sv-retry")
      Application.put_env(:discordia_signaling, :test_room_service_result, {:error, :unavailable})

      assert :retry = suspend_server("sv-retry", 1)
      assert VoiceSessionRegistry.active_room("sv-retry-user") == "voice:sv-retry-room"
      assert SuspensionVersions.newer?({:server, "sv-retry"}, 1)

      Application.put_env(:discordia_signaling, :test_room_service_result, :ok)

      assert :ack = suspend_server("sv-retry", 1)
      assert VoiceSessionRegistry.active_room("sv-retry-user") == nil
    end

    test "acks when LiveKit no longer has the room" do
      join_server("sv-gone-user", "sv-gone-room", "sv-gone")
      Application.put_env(:discordia_signaling, :test_room_service_result, {:error, :not_found})

      assert :ack = suspend_server("sv-gone", 1)
      assert VoiceSessionRegistry.active_room("sv-gone-user") == nil
    end

    test "a reactivation closes nothing and only records its version" do
      join_server("sv-react-user", "sv-react-room", "sv-react")

      assert :ack =
               process_server(
                 @server_reactivated,
                 signed_server_event(@server_reactivated, "sv-react", 2)
               )

      assert VoiceSessionRegistry.active_room("sv-react-user") == "voice:sv-react-room"
      refute SuspensionVersions.newer?({:server, "sv-react"}, 2)
    end

    test "a suspension older than the reactivation, arriving late, expels nobody" do
      join_server("sv-late-user", "sv-late-room", "sv-late")

      assert :ack =
               process_server(
                 @server_reactivated,
                 signed_server_event(@server_reactivated, "sv-late", 2)
               )

      assert :ack = suspend_server("sv-late", 1)
      assert VoiceSessionRegistry.active_room("sv-late-user") == "voice:sv-late-room"

      assert :ack = suspend_server("sv-late", 3)
      assert VoiceSessionRegistry.active_room("sv-late-user") == nil
    end

    test "acks and does nothing when the signature is missing, invalid or for another event" do
      join_server("sv-safe-user", "sv-safe-room", "sv-safe")
      valid = signed_server_event(@server_suspended, "sv-safe", 1)

      log =
        capture_log([level: :warning], fn ->
          for event <- [
                Map.delete(valid, "signature"),
                %{valid | "signature" => String.duplicate("0", 64)},
                %{valid | "server_id" => "another-server"},
                %{valid | "version" => 9},
                signed_server_event(@server_suspended, "sv-safe", 1, "another-secret")
              ] do
            assert :ack = process_server(@server_suspended, event)
          end

          # A valid suspension replayed as a reactivation, and the deletion request,
          # which this consumer does not handle.
          assert :ack = process_server(@server_reactivated, valid)
          assert :ack = process_server("admin.server_deletion_requested", valid)
        end)

      assert VoiceSessionRegistry.active_room("sv-safe-user") == "voice:sv-safe-room"
      assert SuspensionVersions.newer?({:server, "sv-safe"}, 1)
      assert log =~ "voice_suspension_invalid_signature"
    end

    test "does not expel anyone when the secret is empty" do
      join_server("sv-nosecret-user", "sv-nosecret-room", "sv-nosecret")

      capture_log([level: :warning], fn ->
        event = signed_server_event(@server_suspended, "sv-nosecret", 1)
        assert :ack = process_server(@server_suspended, event, "")
      end)

      assert VoiceSessionRegistry.active_room("sv-nosecret-user") == "voice:sv-nosecret-room"
    end

    test "discards correctly signed events with a bad server_id or version" do
      join_server("sv-bad-user", "sv-bad-room", "sv-bad")

      for {server_id, version} <- [{"", 1}, {"sv-bad", 0}, {"sv-bad", -1}] do
        event = signed_server_event(@server_suspended, server_id, version)
        assert :ack = process_server(@server_suspended, event)
      end

      for version <- ["1", 1.0, nil] do
        event = signed_server_event(@server_suspended, "sv-bad", 1)

        # Signed with an integer version, delivered with another type.
        assert :ack = process_server(@server_suspended, %{event | "version" => version})
      end

      assert VoiceSessionRegistry.active_room("sv-bad-user") == "voice:sv-bad-room"
      assert SuspensionVersions.newer?({:server, "sv-bad"}, 1)
    end

    test "discards broken JSON and payloads that are not objects" do
      for key <- [@server_suspended, @server_reactivated] do
        assert :ack = SuspensionConsumer.process_payload(key, "not-json", @secret)
        assert :ack = SuspensionConsumer.process_payload(key, "[]", @secret)
      end
    end

    test "a user event on the same queue still removes only that user" do
      join_server("sv-user-event", "sv-ue-room", "sv-ue-server")
      join_server("sv-bystander", "sv-ue-room", "sv-ue-server")

      assert :ack = process(signed_payload("sv-user-event", 1))

      assert VoiceSessionRegistry.active_room("sv-user-event") == nil
      assert VoiceSessionRegistry.active_room("sv-bystander") == "voice:sv-ue-room"
    end

    test "a user suspension carrying only a server_id does nothing" do
      join_server("sv-confused", "sv-conf-room", "sv-conf")
      event = signed_server_event(@key, "sv-conf", 1)

      capture_log([level: :warning], fn ->
        assert :ack = process_server(@key, event)
      end)

      assert VoiceSessionRegistry.active_room("sv-confused") == "voice:sv-conf-room"
    end
  end

  describe "connection lifecycle" do
    # The callbacks are called directly with a state map, without a broker.
    defp consumer_state(overrides \\ %{}) do
      Map.merge(
        %{
          url: "amqp://guest:guest@127.0.0.1:1",
          exchange: "discordia.events",
          queue: "voice.test.suspensions",
          secret: @secret,
          connection: nil,
          channel: nil
        },
        overrides
      )
    end

    test "init keeps the options and schedules the first connection attempt" do
      assert {:ok, state} =
               SuspensionConsumer.init(
                 rabbitmq_url: "amqp://example",
                 hmac_secret: @secret,
                 queue: "voice.custom.suspensions"
               )

      assert state.url == "amqp://example"
      assert state.secret == @secret
      assert state.queue == "voice.custom.suspensions"
      assert state.exchange == "discordia.events"
      assert state.connection == nil
      assert state.channel == nil
      assert_receive :connect
    end

    test "init falls back to the default queue and an empty secret" do
      assert {:ok, state} = SuspensionConsumer.init(rabbitmq_url: "amqp://example")

      assert state.queue == "voice.signaling"
      assert state.secret == ""
      assert_receive :connect
    end

    test "a failed connection is logged and retried" do
      state = consumer_state()

      log =
        capture_log([level: :warning], fn ->
          assert {:noreply, ^state} = SuspensionConsumer.handle_info(:connect, state)
        end)

      assert log =~ "voice_suspension_consumer_connect_failed"
      assert_receive :connect, 2_000
    end

    test "a lost connection is dropped and a reconnection is scheduled" do
      state = consumer_state(%{connection: %{pid: self()}, channel: :channel})

      log =
        capture_log([level: :warning], fn ->
          assert {:noreply, next} =
                   SuspensionConsumer.handle_info(
                     {:DOWN, make_ref(), :process, self(), :closed},
                     state
                   )

          assert next.connection == nil
          assert next.channel == nil
        end)

      assert log =~ "voice_suspension_consumer_connection_down"
      assert_receive :connect
    end

    test "ignores the AMQP consume and cancel acknowledgements" do
      state = consumer_state()

      assert {:noreply, ^state} = SuspensionConsumer.handle_info({:basic_consume_ok, %{}}, state)
      assert {:noreply, ^state} = SuspensionConsumer.handle_info({:basic_cancel_ok, %{}}, state)
    end

    test "stops when the broker cancels the consumer" do
      state = consumer_state()

      assert {:stop, :normal, ^state} =
               SuspensionConsumer.handle_info({:basic_cancel, %{}}, state)
    end

    test "terminates cleanly without an AMQP connection" do
      assert :ok = SuspensionConsumer.terminate(:normal, consumer_state())
    end

    test "terminating with a connection that is already gone does not raise" do
      pid = spawn(fn -> :ok end)
      ref = Process.monitor(pid)
      assert_receive {:DOWN, ^ref, :process, ^pid, _}

      state = consumer_state(%{connection: %AMQP.Connection{pid: pid}})

      assert :ok = SuspensionConsumer.terminate(:shutdown, state)
    end
  end
end
